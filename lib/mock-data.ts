/** 从文本池里稳定取一条 */
function pickOne<T>(list: T[], seed: string): T {
  return list[rint(seed, list.length)];
}

/**
 * 生成某一年的年度卡片
 * points + index 用来判断「相对前一年」的趋势，所以必须整条曲线一起传进来。
 */
export function buildYearCard(
  points: LifeLinePoint[],
  index: number,
  dimension: DimensionKey,
  birth: BirthInfo,
): YearCardData {
  const point = points[index];
  const prev = points[index - 1];
  const next = points[index + 1];
  const seed = `${birth.birthDate}|${birth.gender}|${dimension}|${point.year}`;
  const band = bandOf(point.age).name;
  const scoreAt = (p?: LifeLinePoint) => (p ? p[dimension] : undefined);
  const trend = trendOf(scoreAt(prev), scoreAt(point), scoreAt(next));

  // 事件条数：越接近现在写得越具体；童年记得少，所以童年年份从简
  const distance = Math.abs(point.year - CURRENT_YEAR);
  const early = point.age <= 12;
  const maxCount = early ? 4 : distance <= 3 ? 6 : distance <= 15 ? 5 : 4;
  const pool = EVENT_POOL[dimension][band] ?? EVENT_POOL[dimension]['职业探索期'] ?? [];
  const events = pickN(pool, Math.min(maxCount, pool.length), `${seed}|ev`).map((text, i) => ({
    text,
    priority: i + 1,
  }));

  const judgmentPool =
    JUDGMENT_POOLS[judgeBandOf(point.age)][dimension][trend] ??
    JUDGMENT_POOLS[judgeBandOf(point.age)][dimension]['震荡'] ??
    ['这一年先把手上确定的事做好，不用急着下结论'];
  const daxian = daxianOf(point.age);

  // 紫微与八字各取一条，并按两条信号的倾向判断「是否互相印证」
  const ziweiPick = pickOne(ZIWEI_SIGNALS, `${seed}|zw`);
  const baziPick = pickOne(BAZI_SIGNALS, `${seed}|bz`);
  const consistency: Consistency =
    ziweiPick.tone === baziPick.tone
      ? '一致'
      : ziweiPick.tone === 'mixed' || baziPick.tone === 'mixed'
        ? '单信号'
        : '冲突';

  return {
    year: point.year,
    age: point.age,
    daxian: daxian.label,
    phase: point.phase,
    trend,
    mainJudgment: pickOne(judgmentPool, `${seed}|jd`),
    events,
    ziweiSignal: ziweiPick.text.replace('{宫}', daxian.palace),
    baziSignal: baziPick.text,
    consistency,
    actionTip: ACTION_POOL[trend],
  };
}

