type JudgeBand = 'early' | 'young' | 'adult';

const JUDGE_BAND_LABEL: Record<JudgeBand, string> = {
  early: '成长期（1-18 岁）',
  young: '起步期（19-32 岁）',
  adult: '成熟期（33 岁以上）',
};

export function judgeBandLabel(band: JudgeBand): string {
  return JUDGE_BAND_LABEL[band];
}

function judgeBandOf(age: number): JudgeBand {
  if (age <= 18) return 'early';
  if (age <= 32) return 'young';
  return 'adult';
}

