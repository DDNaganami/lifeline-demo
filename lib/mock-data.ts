/** 各维度的节律波形：[主周期(年), 主振幅, 相位偏移, 次周期(年), 次振幅, 相位偏移] */
const WAVE: Record<DimensionKey, [number, number, number, number, number, number]> = {
  overall: [11, 4, 0, 4.5, 1.2, 1.1],
  career: [13, 6, 1.2, 5, 1.4, 2.2],
  wealth: [9, 5, 2.4, 3.5, 1.3, 3.3],
  marriage: [7, 5.5, 3.6, 3, 1.6, 4.4],
  parents: [15, 4.5, 4.8, 6, 1.2, 5.5],
  health: [12, 6, 6.0, 5.5, 1.5, 0.7],
};

function shapeValue(dim: DimensionKey, age: number): number {
  const shape = SHAPE[dim];
  if (age <= shape[0][0]) return shape[0][1];
  const last = shape[shape.length - 1];
  if (age >= last[0]) return last[1];
  for (let i = 0; i < shape.length - 1; i++) {
    const [a0, v0] = shape[i];
    const [a1, v1] = shape[i + 1];
    if (age >= a0 && age <= a1) {
      return v0 + (v1 - v0) * smoothstep((age - a0) / (a1 - a0));
    }
  }
  return last[1];
}

/**
 * 单点取值：长期形状 + 个人节律（两条正弦叠加） + 整体抬升或压低。
 * 刻意不加「逐年随机抖动」，否则曲线会长满毛刺、不像人生轨迹。
 */
function scoreAt(dim: DimensionKey, age: number, personSeed: string, birthYear: number): number {
  const base = shapeValue(dim, age);
  const [p1, a1, ph1, p2, a2, ph2] = WAVE[dim];
  const wave =
    Math.sin((age / p1) * Math.PI * 2 + ph1) * a1 +
    Math.sin((age / p2) * Math.PI * 2 + ph2) * a2;
  // 每个人的整体抬升/压低（同一份出生信息固定不变）
  const offset = (rng(`${personSeed}|${birthYear}|${dim}`) - 0.5) * 8;
  return round1(Math.max(5, Math.min(97, base + wave + offset)));
}

function trendOf(prev?: number, cur?: number, next?: number): Trend {
  if (prev === undefined) return '转折';
  const deltas: number[] = [cur! - prev];
  if (next !== undefined) deltas.push(next - cur!);
  const dirs = new Set(deltas.map((d) => (d > 2.5 ? 1 : d < -2.5 ? -1 : 0)));
  if (dirs.size > 1) return '震荡';
  const d = deltas[0];
  if (d > 2.5) return '上升';
  if (d < -2.5) return '下降';
  // 数值平稳时，看是不是有明显高低差的主峰或主谷（要求至少 2 分的落差）
  if (next !== undefined && prev !== undefined) {
    const isPeak = cur! - Math.min(prev, next) >= 2;
    const isValley = Math.max(prev, next) - cur! >= 2;
    if (isPeak || isValley) return '转折';
  }
  return '震荡';
}

/** 生成从 1 岁到 88 岁的完整曲线 */
export function buildLifeLine(birth: BirthInfo): LifeLinePoint[] {
  const birthYear = Number(birth.birthDate.slice(0, 4)) || CURRENT_YEAR - 35;
  const personSeed = `${birth.birthDate}|${birth.birthTime}|${birth.gender}`;
  const dims: DimensionKey[] = ['overall', 'career', 'wealth', 'marriage', 'parents', 'health'];

  const raw = new Map<DimensionKey, number[]>();
  for (const dim of dims) {
    const list: number[] = [];
    for (let age = MIN_AGE; age <= MAX_AGE; age++) {
      list.push(scoreAt(dim, age, personSeed, birthYear));
    }
    raw.set(dim, list);
  }

  const points: LifeLinePoint[] = [];
  for (let age = MIN_AGE; age <= MAX_AGE; age++) {
    const i = age - MIN_AGE;
    const overallList = raw.get('overall')!;
    const get = (dim: DimensionKey, j: number) => raw.get(dim)![j];
    points.push({
      age,
      year: birthYear + age,
      overall: overallList[i],
      career: get('career', i),
      wealth: get('wealth', i),
      marriage: get('marriage', i),
      parents: get('parents', i),
      health: get('health', i),
      phase: phaseOf(age),
      trend: trendOf(
        i > 0 ? overallList[i - 1] : undefined,
        overallList[i],
        i < overallList.length - 1 ? overallList[i + 1] : undefined,
      ),
    });
  }
  return points;
}

export function scoresOf(point: LifeLinePoint): DimensionScores {
  return {
    overall: point.overall,
    career: point.career,
    wealth: point.wealth,
    marriage: point.marriage,
    parents: point.parents,
    health: point.health,
  };
}

