/* =========================== 反馈取用 =========================== */

/**
 * 距离当前年份最近的一条历史反馈，用于「问陈老师」上下文。
 * 没有反馈时返回 undefined。
 */
export function nearestFeedbackYear(
  feedbackYears: number[],
  targetYear: number,
): number | undefined {
  if (feedbackYears.length === 0) return undefined;
  return [...feedbackYears].sort(
    (a, b) => Math.abs(a - targetYear) - Math.abs(b - targetYear),
  )[0];
}

/**
 * 找下一个「还没核对过」的年份：从最近的一年往回找。
 * 全部核对完则返回 undefined。
 */
export function nextUnreviewedYear(
  currentYear: number,
  minAge: number,
  reviewedYears: number[],
): number | undefined {
  const reviewed = new Set(reviewedYears);
  for (let year = currentYear; year >= currentYear - 88 + minAge; year--) {
    if (!reviewed.has(year)) return year;
  }
  return undefined;
}
