export interface Daxian {
  from: number;
  to: number;
  palace: string;
  label: string;
}

/** 大限：2 岁起运，10 年一换 */
export function daxianOf(age: number): Daxian {
  const index = Math.max(0, Math.floor((age - 2) / 10));
  const from = 2 + index * 10;
  const palace = PALACES[index % PALACES.length];
  return {
    from,
    to: from + 9,
    palace,
    label: `${from}-${from + 9} 岁 · ${palace}大限`,
  };
}

/* ======================= 稳定随机（同一人结果不变） ======================= */

function hash(str: string): number {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** 稳定随机数：0 ≤ r < 1 */
function rng(seed: string): number {
  return hash(seed) / 4294967296;
}

/** 稳定随机整数：0 ≤ n < max */
function rint(seed: string, max: number): number {
  return Math.floor(rng(seed) * max);
}

function pickN<T>(list: T[], count: number, seed: string): T[] {
  const pool = [...list];
  const out: T[] = [];
  const n = Math.min(count, pool.length);
  for (let i = 0; i < n; i++) {
    const idx = rint(`${seed}#${i}`, pool.length);
    out.push(pool[idx]);
    pool.splice(idx, 1);
  }
  return out;
}

function round1(n: number): number {
  return Math.round(n * 10) / 10;
}

function smoothstep(t: number): number {
  const x = Math.min(1, Math.max(0, t));
  return x * x * (3 - 2 * x);
}

