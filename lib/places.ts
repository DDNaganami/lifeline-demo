/** 按省份分组后的城市表（用于选择器） */
export function groupCities(): CityGroup[] {
  const map = new Map<string, string[]>();
  for (const [city, prov] of Object.entries(CITY_PROVINCE)) {
    if (!map.has(prov)) map.set(prov, []);
    map.get(prov)!.push(city);
  }
  const groups: CityGroup[] = [];
  for (const prov of GROUP_ORDER) {
    const cities = map.get(prov);
    if (cities) {
      groups.push({ province: prov, cities });
      map.delete(prov);
    }
  }
  // 兜底：没在 GROUP_ORDER 里列到的（新增城市时忘了加顺序也不会丢）
  for (const [prov, cities] of map) groups.push({ province: prov, cities });
  return groups;
}

/**
 * 展示顺序总表。
 * 界面上的分组直接用它，所以不需要再导出「省份列表」这种派生数据。
 */
export function provinceOfCity(city: string): string | undefined {
  return CITY_PROVINCE[city];
}
