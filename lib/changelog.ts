/**
 * 修改日志
 * ---------------------------------------------------------------
 * 给不看代码的同事看：每次改动**解决了什么问题**，而不是"改了什么文件"。
 *
 * 写法约定：
 *   1. 一条日志 = 一个可感知的变化（不是一次提交）
 *   2. 说结果，不说技术（"曲线现在会随出生地变化"，而不是"重构了 signals 层"）
 *   3. 「修复」类条目要说清**原来错在哪**——这是同事最关心的
 *
 * 新增日志时写在数组**最前面**。
 */

export type ChangeKind = 'new' | 'fix' | 'improve' | 'data';

export interface ChangelogItem {
  kind: ChangeKind;
  /** 一句话说明改了什么 */
  what: string;
  /** 为什么改 / 解决了什么问题（可选，但建议写） */
  why?: string;
}

export interface ChangelogEntry {
  date: string; // YYYY-MM-DD
  title: string;
  /** 这一轮的一句话总结 */
  summary: string;
  items: ChangelogItem[];
  /** 这一轮之后，哪些是真的、哪些还是模拟 */
  status?: { real: string[]; mock: string[] };
}

